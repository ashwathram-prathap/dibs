import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';
const { parse } = opentype;
const data = readFileSync('public/fonts/archivo-og.woff');
const font = parse(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
let x = 0;
let path = '';
for (const ch of 'dibs') {
  const g = font.charToGlyph(ch);
  path += g.getPath(x, 84, 110).toPathData(2);
  x += ((g.advanceWidth || 0) * 110) / font.unitsPerEm;
}
const width = Math.ceil(x);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width + 26} 100"><path fill="currentColor" d="${path}"/><path fill="#E1462B" d="M${width + 3} 67h18v18h-18z"/></svg>`;
writeFileSync(
  'shared/brand.ts',
  `// Generated by scripts/build-wordmark.ts from the self-hosted Archivo Black face.\nexport const WORDMARK_WIDTH = ${width + 26};\nexport const WORDMARK_PATH = ${JSON.stringify(path)};\nexport const WORDMARK_BLOCK_X = ${width + 3};\n`,
);
writeFileSync('public/favicon.svg', svg.replace('currentColor', '#1A1A17'));
