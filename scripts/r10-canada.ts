const report = [];
for (const [slug, words] of Object.entries(canada)) {
  const c = readCategory(`categories/${slug}.json`),
    keys = new Map<string, string>();
  for (const a of c.answers)
    for (const k of [a.display, ...a.aliases]) keys.set(normalize(k), a.display);
  report.push({
    slug,
    checked: words.length,
    rows: words.map((answer) => ({ answer, accepted: keys.get(normalize(answer)) || null })),
    missing: words.filter((w) => !keys.has(normalize(w))),
  });
}
writeFileSync('review/round10/canada-coverage.json', JSON.stringify(report, null, 2));
